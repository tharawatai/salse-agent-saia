# أنماط اللوحات السعودية المختلفة
PLATE_PATTERNS = [
    # نمط: حروف عربية مفصولة بمسافات + أرقام (أ ب ج 1234)
    r'لوحة\s*([أ-ي]\s+[أ-ي]\s+[أ-ي]\s+\d{1,4})',
    r'اللوحة\s*([أ-ي]\s+[أ-ي]\s+[أ-ي]\s+\d{1,4})',
    r'([أ-ي]\s+[أ-ي]\s+[أ-ي]\s+\d{1,4})',
    # نمط: حروف عربية متصلة + أرقام (أبج 1234)
    r'لوحة\s*([أ-ي]{2,3}\s*\d{1,4})',
    r'([أ-ي]{2,3}\s+\d{1,4})',
    # نمط: حروف إنجليزية + أرقام (ABC 1234)
    r'لوحة\s*([A-Za-z]{2,3}\s*\d{1,4})',
    r'([A-Za-z]{2,3}\s+\d{1,4})',
    # نمط: أرقام + حروف (1234 ABC أو 1234 أ ب ج)
    r'(\d{1,4}\s+[A-Za-z]{2,3})',
    r'(\d{1,4}\s+[أ-ي]\s+[أ-ي]\s+[أ-ي])',
    r'(\d{1,4}\s+[أ-ي]{2,3})',
]

# أنماط استخراج القيمة
VALUE_PATTERNS = [
    r'(\d{1,3}(?:,\d{3})+)\s*(?:ريال|ر\.س)?',  # مع فواصل: 100,000
    r'(\d{5,})\s*(?:ريال|ر\.س)?',  # بدون فواصل: 100000
]

# نمط استخراج السنة
