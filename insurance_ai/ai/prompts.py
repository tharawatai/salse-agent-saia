def is_advisory_question(message: str) -> bool:
    """
    التحقق إذا كانت الرسالة سؤال استشاري
    
    Args:
        message: رسالة العميل
    
    Returns:
        bool: True إذا كان سؤال استشاري
    """
    message_lower = message.lower().strip()
    return any(keyword in message_lower for keyword in ADVISORY_KEYWORDS)


def is_comparison_question(message: str) -> bool:
    """
    التحقق إذا كانت الرسالة سؤال مقارنة
    
    Args:
        message: رسالة العميل
    
    Returns:
        bool: True إذا كان سؤال مقارنة
    """
    message_lower = message.lower().strip()
    return any(keyword in message_lower for keyword in COMPARISON_KEYWORDS)


